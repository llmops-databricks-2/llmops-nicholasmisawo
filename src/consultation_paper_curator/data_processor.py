"""Parse downloaded consultation papers with ai_parse_document, then chunk and embed them for retrieval.

silver_consultation_papers (volume_path set by the silver job's download step)
   ↓ (parse_pending_papers)
silver_parsed_consultation_papers (ai_parse_document JSON)
   ↓ (chunk_parsed_papers)
gold_consultation_paper_chunks (clean text + paper metadata + embedding, Change Data Feed on)
   └─ (Vector Search Delta Sync index, built in a later lecture)

Downloading lives in download.py and the silver notebook, so this module only reads files already in the
volume. The chunk-extraction rules are pure functions so they can be unit tested without Spark.
"""

import json
import re
from datetime import UTC, datetime
from typing import NamedTuple

from loguru import logger
from pyspark.sql import DataFrame, SparkSession
from pyspark.sql.functions import col, concat_ws, explode, expr, lit, regexp_replace, udf
from pyspark.sql.types import ArrayType, IntegerType, StringType, StructField, StructType

from consultation_paper_curator.config import ProjectConfig
from consultation_paper_curator.download import processed_stamp
from consultation_paper_curator.schemas import CHUNKS_SCHEMA, PARSED_SCHEMA
from consultation_paper_curator.tables import KEY, ensure_table

# Element types kept as chunks. Tables carry fee schedules and capital requirements, so they're kept;
# titles, headers, footers and page numbers are boilerplate or too short to retrieve on their own.
CHUNK_ELEMENT_TYPES = ("text", "table")
# Figure descriptions are generated by a model per element; turning them off keeps parsing cheap
PARSE_OPTIONS = "map('version', '2.0', 'descriptionElementTypes', '')"

CHUNK_UDF_SCHEMA = ArrayType(
    StructType(
        [
            StructField("chunk_id", StringType(), True),
            StructField("page_id", IntegerType(), True),
            StructField("text", StringType(), True),
        ]
    )
)


class Chunk(NamedTuple):
    """One retrievable piece of a parsed paper."""

    chunk_id: str
    page_id: int | None
    text: str


def clean_chunk(text: str) -> str:
    """Rejoin words hyphenated across line breaks and collapse newlines and repeated whitespace."""
    # "docu-\nments" -> "documents"
    joined = re.sub(r"(\w)-\s*\n\s*(\w)", r"\1\2", text or "")
    return re.sub(r"\s+", " ", joined).strip()


def _first_page(element: dict) -> int | None:
    boxes = element.get("bbox") or []
    return boxes[0].get("page_id") if boxes else None


def extract_chunks(parsed_content_json: str | None) -> list[Chunk]:
    """Return the cleaned, non-empty CHUNK_ELEMENT_TYPES elements of an ai_parse_document result."""
    if not parsed_content_json:
        return []

    elements = json.loads(parsed_content_json).get("document", {}).get("elements", [])
    chunks = []
    for element in elements:
        if element.get("type") not in CHUNK_ELEMENT_TYPES:
            continue
        text = clean_chunk(element.get("content", ""))
        if text:
            chunks.append(Chunk(str(element.get("id", "")), _first_page(element), text))
    return chunks


class DataProcessor:
    """Turn the downloaded papers in silver into embedded chunks, processing each paper once.

    Every step is incremental: a paper is parsed once its file is in the volume and chunked once it's
    parsed, so re-runs only pick up papers the last run hadn't reached.
    """

    def __init__(self, spark: SparkSession, config: ProjectConfig) -> None:
        self.spark = spark
        self.cfg = config
        self.papers_table = f"{config.full_schema_name}.silver_consultation_papers"
        self.parsed_table = f"{config.full_schema_name}.silver_parsed_consultation_papers"
        self.chunks_table = f"{config.full_schema_name}.gold_consultation_paper_chunks"
        self.run_stamp = processed_stamp(datetime.now(UTC))

    def ensure_tables(self) -> None:
        """Create the parsed and chunks tables if missing; the chunks table feeds a Delta Sync index."""
        if not self.spark.catalog.tableExists(self.papers_table):
            raise RuntimeError(
                f"{self.papers_table} not found; run the silver_consultation_papers task of consultation_papers_pipeline first"
            )

        ensure_table(
            self.spark,
            self.parsed_table,
            PARSED_SCHEMA,
            layer="silver",
            comment="Silver: ai_parse_document output for each downloaded consultation paper, parsed once.",
        )
        ensure_table(
            self.spark,
            self.chunks_table,
            CHUNKS_SCHEMA,
            layer="gold",
            comment="Gold: cleaned text and table chunks of consultation papers with paper metadata and "
            f"{self.cfg.embedding_endpoint} embeddings; the source of the vector search index.",
        )
        self.spark.sql(f"ALTER TABLE {self.chunks_table} SET TBLPROPERTIES (delta.enableChangeDataFeed = true)")

    def remove_dropped_papers(self) -> None:
        """Delete parsed rows and chunks of papers silver no longer holds (filtered out or superseded).

        Without this, the index would keep answering from a duplicate silver has since replaced.
        """
        for table in (self.parsed_table, self.chunks_table):
            self.spark.sql(f"""
                DELETE FROM {table}
                WHERE {KEY} NOT IN (SELECT {KEY} FROM {self.papers_table})
            """)

    def _papers_to_parse(self) -> DataFrame:
        downloaded = self.spark.table(self.papers_table).where(col("volume_path").isNotNull())
        parsed = self.spark.table(self.parsed_table).select(KEY)
        return downloaded.join(parsed, KEY, "left_anti").select(KEY, "volume_path")

    def parse_pending_papers(self) -> int:
        """Parse downloaded papers not yet in the parsed table and append them; return how many."""
        pending = self._papers_to_parse()
        paths = [row.volume_path for row in pending.collect()]
        if not paths:
            logger.info("No downloaded papers waiting to be parsed")
            return 0

        logger.info(f"Parsing {len(paths)} papers with ai_parse_document")
        parsed_df = (
            self.spark.read.format("binaryFile")
            .load(paths)
            # binaryFile reports dbfs:/Volumes/...; silver stores /Volumes/...
            .withColumn("volume_path", regexp_replace(col("path"), "^dbfs:", ""))
            .join(pending, "volume_path")
            .withColumn("parsed", expr(f"ai_parse_document(content, {PARSE_OPTIONS})"))
            .select(
                col(KEY),
                col("volume_path"),
                expr("to_json(parsed)").alias("parsed_content"),
                expr("to_json(parsed:error_status)").alias("parse_errors"),
                lit(self.run_stamp).cast("long").alias("processed"),
            )
        )
        parsed_df.write.format("delta").mode("append").saveAsTable(self.parsed_table)
        return len(paths)

    def _papers_to_chunk(self) -> DataFrame:
        chunked = self.spark.table(self.chunks_table).select(KEY).distinct()
        return self.spark.table(self.parsed_table).join(chunked, KEY, "left_anti")

    def _embed(self, chunks_df: DataFrame) -> DataFrame:
        # ai_query is used via expr: not every runtime exposes it in pyspark.sql.functions
        endpoint = self.cfg.embedding_endpoint.replace("'", "''")
        return chunks_df.withColumn("embedding", expr(f"CAST(ai_query('{endpoint}', text) AS ARRAY<FLOAT>)"))

    def chunk_parsed_papers(self) -> int:
        """Chunk, enrich and embed parsed papers not yet in the chunks table; return the chunks written."""
        extract_chunks_udf = udf(extract_chunks, CHUNK_UDF_SCHEMA)
        metadata_df = self.spark.table(self.papers_table).select(
            KEY,
            "title",
            "doc_kind",
            "institution",
            "published_date",
            "comment_deadline",
            "topics",
            "is_archived",
            "file_url",
        )

        chunks_df = (
            self._papers_to_chunk()
            .withColumn("chunk", explode(extract_chunks_udf(col("parsed_content"))))
            .select(
                col(KEY),
                col("chunk.chunk_id").alias("chunk_id"),
                col("chunk.page_id").alias("page_id"),
                col("chunk.text").alias("text"),
            )
            .withColumn("id", concat_ws("_", col(KEY), col("chunk_id")))
            .withColumn("processed", lit(self.run_stamp).cast("long"))
            .join(metadata_df, KEY)
        )
        embedded = self._embed(chunks_df).select(*CHUNKS_SCHEMA.fieldNames())
        embedded.write.format("delta").mode("append").saveAsTable(self.chunks_table)
        # Counted from the table: serverless can't cache, and recounting the DataFrame would embed twice
        return self.spark.table(self.chunks_table).where(col("processed") == self.run_stamp).count()

    def process_and_save(self) -> None:
        """Run the whole workflow: prepare tables, drop stale papers, parse new files, then chunk them."""
        self.ensure_tables()
        self.remove_dropped_papers()

        parsed = self.parse_pending_papers()
        logger.info(f"Parsed {parsed} papers into {self.parsed_table}")

        written = self.chunk_parsed_papers()
        logger.info(f"Wrote {written} chunks to {self.chunks_table}")
